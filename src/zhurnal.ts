const HOW: Record<string, string> = {
  load: 'сразу (постоянный элемент, не окно)', time: 'через {0} с на странице', pages: '{0}-я страница за визит',
  scroll: 'прокрутка {0}%', block: 'блок {0} на экране', exit: 'курсор ушёл к вкладкам',
};
const CLOSE: Record<string, string> = { x: 'крестиком', esc: 'клавишей Esc', back: 'кнопкой «назад»', bg: 'тапом мимо окна' };

const fill = (s: string, p: unknown[] = []) => s.replace(/\{(\d)\}/g, (_, i) => String(p[+i]));
const obj = (o: unknown) => JSON.stringify(o).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'");
const ev = (n: number) => `${n} ${n % 10 === 1 && n % 100 !== 11 ? 'событие' : [2, 3, 4].includes(n % 10) && ![12, 13, 14].includes(n % 100) ? 'события' : 'событий'}`;

/** Причина простыми словами: «вы с телефона (правило: на телефоне окно на уходе не работает)». */
export function reason(n: { code: string; p?: unknown[] }) {
  const [why, rule] = RULES[n.code] || [n.code, 'нет текста'];
  return `${fill(why, n.p)} (правило: ${fill(rule, n.p)})`;
}

/** Одна строка журнала по записи модуля. */
export function line(k: string, a: any[]): string {
  const w = `«${a[0]}»`;
  if (k === 'not') return `${w} НЕ показываем: ${reason(a[1])}`;
  if (k === 'wait') return `${w} ждёт: ${reason(a[1])}`;
  if (k === 'show') return `${w} показываем: ${fill(HOW[a[1]] || a[1], [a[2]])}`;
  if (k === 'as') return `${w} на телефоне – ${a[1] === 'tab' ? 'ярлычком' : 'плашкой'} вместо окна (правило: на телефоне на странице из поиска окно само не перекрывает страницу)`;
  if (k === 'click') return `${w} открыт по клику (правило: по клику человека открывается всегда)`;
  if (k === 'close') return `${w} закрыт ${CLOSE[a[1]] || a[1]}`;
  if (k === 'armexit') return `${w} ждёт ухода курсора к вкладкам`;
  if (k === 'armpages') return `${w} ждёт ${a[1]}-й страницы визита`;
  if (k === 'cookie') return 'Ждём выбор по cookie: самопоявляющиеся виджеты пока молчат (правило: пока открыто окно cookie, виджеты ждут)';
  if (k === 'lead') return `Заявка отправлена (${a[0]}) → виджеты заявок молчат 90 дней`;
  if (k === 'flush') return 'Выбор по cookie сделан: очередь событий Метрики отправлена';
  if (k === 'send') return `Демо: заявка никуда не уходит, заглушка ответит «принято» через 0,5 с. Ушло бы на сервер: ${JSON.stringify(a[0])}`;
  if (k === 'ym') {
    const [args, left] = a as [unknown[], number];
    const call = args[0] === 'reachGoal' ? `reachGoal('${args[1]}',${obj(args[2])})` : `params(${obj(args[1])})`;
    const head = args[1] === 'lead' ? 'Заявка принята → ' : args[1] === 'contact_click' ? 'Клик по мессенджеру → ' : 'Метрика: ';
    return head + call + (left > 0 ? ` – Метрика ждёт согласия на cookie: ${ev(left)} в очереди` : ' ушёл бы в Метрику');
  }
  return a.join(' ');
}

/** Подключить журнал к списку на странице: новые строки сверху, с временем. */
export function attach(list: HTMLElement) {
  addEventListener('w-log', (e) => {
    const d = (e as CustomEvent).detail;
    const li = document.createElement('li');
    li.textContent = `${new Date().toTimeString().slice(0, 8)}  ${line(d.k, d.a)}`;
    list.prepend(li);
  });
}
